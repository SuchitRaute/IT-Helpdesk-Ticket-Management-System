
-- =========================================
-- NexDesk IT Helpdesk Database Schema
-- Database: HelpdeskDB (Apache Derby)
-- =========================================

CREATE TABLE USERS (
    USER_ID INT NOT NULL GENERATED ALWAYS AS IDENTITY
        (START WITH 1, INCREMENT BY 1),
    FULL_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL,
    PASSWORD_HASH VARCHAR(64) NOT NULL,
    ROLE VARCHAR(20) NOT NULL,
    DEPARTMENT VARCHAR(100),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE CHECK
        (ROLE IN ('ADMIN', 'TECHNICIAN', 'EMPLOYEE'))
);

CREATE TABLE TICKETS (
    TICKET_ID INT NOT NULL GENERATED ALWAYS AS IDENTITY
        (START WITH 1001, INCREMENT BY 1),
    TITLE VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(5000) NOT NULL,
    CATEGORY VARCHAR(100) NOT NULL,
    PRIORITY VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    CREATED_BY INT NOT NULL,
    ASSIGNED_TO INT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_AT TIMESTAMP,
    CONSTRAINT PK_TICKETS PRIMARY KEY (TICKET_ID),
    CONSTRAINT FK_TICKET_CREATOR FOREIGN KEY (CREATED_BY)
        REFERENCES USERS(USER_ID),
    CONSTRAINT FK_TICKET_TECHNICIAN FOREIGN KEY (ASSIGNED_TO)
        REFERENCES USERS(USER_ID),
    CONSTRAINT CK_TICKET_PRIORITY CHECK
        (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT CK_TICKET_STATUS CHECK
        (STATUS IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS',
                    'ON_HOLD', 'RESOLVED', 'CLOSED'))
);

CREATE TABLE TICKET_HISTORY (
    HISTORY_ID INT NOT NULL GENERATED ALWAYS AS IDENTITY
        (START WITH 1, INCREMENT BY 1),
    TICKET_ID INT NOT NULL,
    CHANGED_BY INT NOT NULL,
    OLD_STATUS VARCHAR(20),
    NEW_STATUS VARCHAR(20),
    ACTION_DESCRIPTION VARCHAR(1000),
    CHANGED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TICKET_HISTORY PRIMARY KEY (HISTORY_ID),
    CONSTRAINT FK_HISTORY_TICKET FOREIGN KEY (TICKET_ID)
        REFERENCES TICKETS(TICKET_ID),
    CONSTRAINT FK_HISTORY_USER FOREIGN KEY (CHANGED_BY)
        REFERENCES USERS(USER_ID)
);

CREATE TABLE TICKET_COMMENTS (
    COMMENT_ID INT NOT NULL GENERATED ALWAYS AS IDENTITY
        (START WITH 1, INCREMENT BY 1),
    TICKET_ID INT NOT NULL,
    USER_ID INT NOT NULL,
    COMMENT_TEXT VARCHAR(3000) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TICKET_COMMENTS PRIMARY KEY (COMMENT_ID),
    CONSTRAINT FK_COMMENT_TICKET FOREIGN KEY (TICKET_ID)
        REFERENCES TICKETS(TICKET_ID),
    CONSTRAINT FK_COMMENT_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
);

CREATE INDEX IDX_TICKETS_STATUS
    ON TICKETS(STATUS);

CREATE INDEX IDX_TICKETS_PRIORITY
    ON TICKETS(PRIORITY);

CREATE INDEX IDX_TICKETS_CREATOR
    ON TICKETS(CREATED_BY);

CREATE INDEX IDX_TICKETS_ASSIGNED
    ON TICKETS(ASSIGNED_TO);

CREATE INDEX IDX_HISTORY_TICKET
    ON TICKET_HISTORY(TICKET_ID);

CREATE INDEX IDX_COMMENTS_TICKET
    ON TICKET_COMMENTS(TICKET_ID);